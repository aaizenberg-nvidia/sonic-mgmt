def create_lossy_lossless_json_traffic_file(player_alias, traffic_parameters, json_path, num_lossy_packets, num_lossless_packets, chip_type):
    traffic_parameters["num_packets"] = num_lossy_packets if chip_type != "SPC6" else int(num_lossy_packets * 1.5)
    lossy_stream = create_json_traffic_stream(player_alias, traffic_parameters, f"{player_alias}_lossy_stream",
                                              dscp_to_tc(traffic_parameters["lossy_dscp_value"], 2))

    traffic_parameters["num_packets"] = num_lossless_packets if chip_type != "SPC6" else int(num_lossless_packets * 1.5)
    lossless_stream = create_json_traffic_stream(player_alias, traffic_parameters, f"{player_alias}_lossless_stream",
                                                 dscp_to_tc(traffic_parameters["lossless_dscp_value"], 2))

    create_json_traffic_file_with_stream_list(player_alias, traffic_parameters, json_path,
                                              stream_list=[lossy_stream, lossless_stream])


def create_burst_json_traffic_stream(player_alias, traffic_parameters, burst_config, bonus_ports):
    """
    Creates the traffic stream that seeds the burst generated by the bonus ports.

    The bonus ports are the generators of this stream, so its ports are the bonus ports rather than the
    mloop ports the main traffic uses. How far the burst gets is capped by the ingress policer the SDK bound
    to the bonus ports from the same burst configuration.

    Args:
        player_alias: Alias of the traffic generator the stream is built for.
        traffic_parameters: Traffic parameters of the player, used for everything but the fields the burst
                            configuration overrides.
        burst_config: BurstConfig of the scenario.
        bonus_ports: Bonus ports of the player, generating the burst.

    Returns:
        dict: JSON representation of the burst traffic stream.
    """
    burst_parameters = dict(traffic_parameters, ports=bonus_ports, packet_size=burst_config.packet_size,
                            num_packets=burst_config.num_packets)
    return create_json_traffic_stream(player_alias, burst_parameters, f"{player_alias}_burst_stream",
                                      dscp_to_tc(burst_config.dscp, 2))


def get_lossy_lossless_basic_traffic(players, conf_args, num_lossy_packets, num_lossless_packets, chip_type,
                                     template_suite="traffic_packets_json_files"):
    traffic_jsons = {}
    pkt_size = PerfConsts.PACKET_SIZE_LIST[0]
    for player_alias in PerfConsts.PERF_SETUP_TG_ALIASES:
        player_cli_obj = players[player_alias]['cli']
        json_path = os.path.join(BugHandlerConst.NGTS_PATH, "performance_tests", template_suite,
                                 TESTS_SCENARIO, f"{player_alias}_{TESTS_SCENARIO.replace('/', '_')}_{pkt_size}.json")
        traffic_parameters = get_lossy_lossless_traffic_parameters(player_cli_obj, conf_args)
        create_lossy_lossless_json_traffic_file(player_alias=player_alias, traffic_parameters=traffic_parameters,
                                                json_path=json_path, num_lossy_packets=num_lossy_packets,
                                                num_lossless_packets=num_lossless_packets, chip_type=chip_type)
        traffic_jsons[player_alias] = json_path
    return traffic_jsons


def get_lossy_lossless_burst_traffic(players, conf_args, burst_config,
                                     template_suite="traffic_packets_json_files"):
    """
    Builds the burst traffic JSON of each traffic generator, as a file of its own per player.

    The burst is kept out of the main traffic JSON because the two are not played at the same time: the main
    traffic has to reach its steady state first, and only then is the burst injected on top of it. A single
    JSON would seed the bonus port loops during ramp up instead.

    Args:
        players: Performance setup players.
        conf_args: Configuration arguments of the test.
        burst_config: BurstConfig of the scenario.

    Returns:
        dict: Burst traffic JSON path per traffic generator alias.
    """
    burst_jsons = {}
    for player_alias in PerfConsts.PERF_SETUP_TG_ALIASES:
        player_cli_obj = players[player_alias]['cli']
        json_path = os.path.join(BugHandlerConst.NGTS_PATH, "performance_tests", template_suite, TESTS_SCENARIO,
                                 f"{player_alias}_{TESTS_SCENARIO.replace('/', '_')}_"
                                 f"{BurstConfigConsts.BURST_SCENARIO_SUFFIX}.json")
        traffic_parameters = get_lossy_lossless_traffic_parameters(player_cli_obj, conf_args)
        bonus_ports = get_burst_bonus_ports(player_cli_obj, player_alias)
        burst_stream = create_burst_json_traffic_stream(player_alias, traffic_parameters, burst_config, bonus_ports)
        create_json_traffic_file_with_stream_list(player_alias, traffic_parameters, json_path,
                                                  stream_list=[burst_stream])
        burst_jsons[player_alias] = json_path
    return burst_jsons


def get_lossy_lossless_traffic_parameters(player_cli_obj, conf_args):
    """Traffic parameters of a player, with the dscp values the lossy and lossless streams ride on."""
    traffic_parameters = player_cli_obj.performance.get_traffic_parameters(
        scenario=TESTS_SCENARIO, conf_args=conf_args)
    traffic_parameters.update({"lossy_dscp_value": PerfConsts.DVS_LOSSY_TC,
                               "lossless_dscp_value": PerfConsts.DVS_LOSSLESS_TC})
    return traffic_parameters


def get_burst_bonus_ports(player_cli_obj, player_alias):
    """
    Returns the bonus ports generating the burst on a player, failing when the chip has none.

    A chip without bonus ports (SPC1/2/3) has nothing to generate a burst from, which would silently turn a
    burst scenario into its burst free equivalent instead of testing what it claims to.
    """
    bonus_ports = player_cli_obj.performance.get_bonus_ports()
    if not bonus_ports:
        raise TestIssue(f"Cannot generate a burst on {player_alias}: its chip has no bonus ports to generate "
                        f"the burst from")
    return bonus_ports


